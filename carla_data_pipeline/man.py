def _unwrap_optional(annotation):
    """Return (inner_annotation, is_optional)."""
    if typing.get_origin(annotation) in (typing.Union, types.UnionType):
        args = [a for a in typing.get_args(annotation) if a is not type(None)]
        if len(args) == 1:
            return args[0], True
    return annotation, False


def _nested_model(annotation):
    """The BaseModel subclass inside annotation (direct, Optional or list), if any."""
    annotation, _ = _unwrap_optional(annotation)
    if typing.get_origin(annotation) is list:
        annotation = typing.get_args(annotation)[0]
    if isinstance(annotation, type) and issubclass(annotation, BaseModel):
        return annotation
    return None


def _type_name(annotation):
    annotation, optional = _unwrap_optional(annotation)
    suffix = " | none" if optional else ""
    if typing.get_origin(annotation) is typing.Literal:
        return " | ".join(repr(a) for a in typing.get_args(annotation)) + suffix
    if typing.get_origin(annotation) is list:
        return f"list of {_type_name(typing.get_args(annotation)[0])}" + suffix
    if isinstance(annotation, type):
        return annotation.__name__ + suffix
    return str(annotation) + suffix


def render_config(model: type[BaseModel] = CollectConfig, indent: int = 0) -> str:
    lines = []
    if indent == 0:
        lines.append("Scenario config reference (generated from the Pydantic schema).")
        lines.append("Sections nest as shown; unknown keys are rejected everywhere.")
        lines.append("")
    pad = "  " * indent
    for name, field in model.model_fields.items():
        nested = _nested_model(field.annotation)
        if field.is_required():
            tail = "(required)"
        elif nested or field.default is PydanticUndefined or field.default is None:
            tail = ""
        else:
            tail = f"= {field.default!r}"
        head = f"{pad}{name}: {_type_name(field.annotation)} {tail}".rstrip()
        lines.append(head)
        if field.description:
            lines.extend(textwrap.wrap(field.description, width=76,
                                       initial_indent=pad + "    ",
                                       subsequent_indent=pad + "    "))
        if nested:
            lines.append(render_config(nested, indent + 1))
    return "\n".join(lines)


def render(topic: str) -> str:
    return USAGE if topic == "usage" else render_config()
